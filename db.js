// Connexion PostgreSQL partagée par le serveur et le script de migration.
// Réglages lus dans DATABASE_URL (hébergeur) ou, à défaut, PGHOST / PGPORT / PGUSER / PGPASSWORD / PGDATABASE.
const { Pool, types } = require('pg');

// Dates renvoyées telles quelles ("2026-10-23", "2026-10-22 21:33:03") plutôt qu'en objets Date décalés par le fuseau
types.setTypeParser(types.builtins.DATE, (v) => v);
types.setTypeParser(types.builtins.TIMESTAMP, (v) => v);

const pool = new Pool({ connectionString: process.env.DATABASE_URL });

async function initSchema() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS reservations (
      id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      created_at   TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
      name         TEXT NOT NULL,
      phone        TEXT NOT NULL,
      service      TEXT NOT NULL,
      day          DATE NOT NULL,
      slot         TEXT NOT NULL,
      status       TEXT NOT NULL DEFAULT 'nouvelle',
      notified     BOOLEAN NOT NULL DEFAULT FALSE,
      notify_error TEXT
    )
  `);
}

module.exports = { pool, initSchema };
